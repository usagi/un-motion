import assert from 'node:assert/strict';
import { ProfileSyncFeedback, mergeProfileSyncWarnings } from '../src/lib/profileSync.ts';
const feedback=new ProfileSyncFeedback();
const target=(id,accepted)=>({capturerId:id,accepted,error:accepted?null:'offline',statusCode:accepted?200:503});
const report=targets=>({id:'a',name:'A',syncReport:{targets,discoveryError:null}});
let error=feedback.update(report([target(1,false)]),'ja-JP','');
error=feedback.update(report([target(2,false)]),'ja-JP',error);
assert.match(error,/Capturer #1/,'An absent failed recipient must remain visible');
assert.match(error,/Capturer #2/);
error=feedback.update(report([target(2,true)]),'ja-JP',error);
assert.match(error,/Capturer #1/,'Recovering another recipient must not clear the first');
assert.doesNotMatch(error,/Capturer #2/);
error=feedback.update(report([target(1,true)]),'ja-JP',error);
assert.equal(error,'');
console.log('PASS: missing failed recipients persist across partial reports; acknowledgements clear only their own recipient');

const multi = new ProfileSyncFeedback();
const named = (id, targets) => ({id, name:id, syncReport:{targets, discoveryError:null}});
let combined = multi.update(named('a',[target(10,false)]),'ja-JP','unrelated error');
combined = multi.update(named('b',[target(20,false)]),'ja-JP',combined);
assert.match(combined,/Capturer #10/,'Another profile failure must not hide the first');
assert.match(combined,/Capturer #20/);
assert.match(combined,/unrelated error/);
combined = multi.update(named('b',[target(20,true)]),'ja-JP',combined);
assert.match(combined,/Capturer #10/,'Recovering B must keep A visible');
assert.doesNotMatch(combined,/Capturer #20/);
combined = multi.update(named('a',[target(10,true)]),'ja-JP',combined);
assert.equal(combined,'unrelated error');
console.log('PASS: profile-specific acknowledgements preserve other profiles and unrelated errors');

let retained=[];
const persistent=new ProfileSyncFeedback(warnings=>{retained=warnings;});
const initial=persistent.update(named('a',[target(3,false)]),'ja-JP','');
assert.match(mergeProfileSyncWarnings('',retained),/Capturer #3/,'Clearing an ordinary banner cannot erase delivery evidence');
assert.match(mergeProfileSyncWarnings('new failure',retained),/new failure/);
assert.match(mergeProfileSyncWarnings('new failure',retained),/Capturer #3/);
assert.equal(mergeProfileSyncWarnings(initial,retained),initial,'Do not duplicate the ordinary banner');
persistent.update({id:'a',name:'a'},'ja-JP','');
assert.equal(retained.length,1,'Missing report is not acknowledgement');
persistent.update(named('a',[]),'ja-JP','');assert.equal(retained.length,1);
persistent.update(named('a',[target(3,true)]),'ja-JP','');assert.deepEqual(retained,[]);
assert.equal(mergeProfileSyncWarnings('new failure',retained),'new failure');
console.log('PASS: retained delivery evidence survives ordinary banner reset and clears only on acknowledgement');
